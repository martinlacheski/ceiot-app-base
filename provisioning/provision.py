#!/usr/bin/env python3
"""Provision a CEIoT environmental device (ESP32) end to end.

`prepare` does, in order:

1. Device record through the backend API (admin token):
   - without --serial: POST /api/provisioning/devices/prepare reserves a new
     serial (generated by the backend) and installs the variant's sensor;
   - with --serial: reuses that device, or registers it (with the sensor) with
     POST /api/devices.
2. Reconciles the record with the firmware variant (--sensor): environmental
   device type, optional name, pairing to an environment (--environment-id /
   --environment-of) and exactly one active installed sensor of that model
   with the key the firmware publishes (dht11/dht22/bmp280/bme280). The device
   sensors API only serves paired devices: an unpaired device keeps the sensor
   it was registered with.
3. Client certificate CN=<serial> from mqtt/pki (issued with
   emitir-certificado-dispositivo.sh, or reused after checking it against the
   CA and the serial).
4. Stages provisioning/build/<serial>/cert/{root.crt, client.crt, client.key,
   serial.txt, provisioning.json} and copies it to esp32/cert/ (the firmware
   packs those files into the LittleFS image).
5. Prints (or, with --flash PORT, runs) the build and flash commands.

Only the Python standard library is used. The API token is read from the
environment or from provisioning/.env.local (see login.py) and never printed.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path
from urllib import error, parse, request

PROVISIONING_DIR = Path(__file__).resolve().parent
REPO_ROOT = PROVISIONING_DIR.parent
DEFAULT_ENV_FILE = PROVISIONING_DIR / ".env.local"
DEFAULT_PROFILE = PROVISIONING_DIR / "profiles" / "local.json"
DEFAULT_STAGING_ROOT = PROVISIONING_DIR / "build"
DEFAULT_PKI_DIR = REPO_ROOT / "mqtt" / "pki"
FIRMWARE_DIR = REPO_ROOT / "esp32"
DEFAULT_FIRMWARE_CERT_DIR = FIRMWARE_DIR / "cert"
DEFAULT_API_BASE_URL = "http://localhost:18000"
IDF_ACTIVATE = "~/.espressif/tools/activate_idf_v6.1.sh"

ENVIRONMENTAL_TYPE_CODE = "environmental"
SENSORS = {"dht11": "DHT11", "dht22": "DHT22", "bmp280": "BMP280", "bme280": "BME280"}
CERT_FILES = ("root.crt", "client.crt", "client.key")
STAGED_FILES = CERT_FILES + ("serial.txt", "provisioning.json")
PROFILE_FIELDS = ("mqtt_uri", "mqtt_port", "mqtt_use_tls")
SERIAL_RE = re.compile(r"^IOT-[0-9A-Z]{4}-[0-9A-Z]{4}$")


class ProvisioningError(RuntimeError):
    pass


# --- configuration ------------------------------------------------------------

def parse_env_file(path: Path) -> dict[str, str]:
    """KEY=value lines (optional `export`, quotes stripped); missing file -> {}."""
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):].strip()
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def resolve_setting(name: str, env_file_values: dict[str, str], default: str | None = None) -> str | None:
    return os.environ.get(name) or env_file_values.get(name) or default


def normalize_serial(value: str) -> str:
    serial = value.strip().upper()
    if not SERIAL_RE.fullmatch(serial):
        raise argparse.ArgumentTypeError(f"invalid serial {value!r}: expected IOT-XXXX-XXXX")
    return serial


def normalize_port(value: object) -> str:
    if isinstance(value, bool):
        raise ProvisioningError("Invalid profile field 'mqtt_port': expected an integer.")
    if isinstance(value, int):
        port = value
    elif isinstance(value, str) and value.strip().isdigit():
        port = int(value.strip())
    else:
        raise ProvisioningError("Invalid profile field 'mqtt_port': expected an integer.")
    if not 1 <= port <= 65535:
        raise ProvisioningError("Invalid profile field 'mqtt_port': expected 1-65535.")
    return str(port)


def normalize_tls(value: object) -> str:
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int) and value in (0, 1):
        return str(value)
    if isinstance(value, str) and value.strip().lower() in {"1", "true", "yes", "on"}:
        return "1"
    if isinstance(value, str) and value.strip().lower() in {"0", "false", "no", "off"}:
        return "0"
    raise ProvisioningError("Invalid profile field 'mqtt_use_tls': expected true/false or 1/0.")


def load_profile(path: Path) -> dict[str, str]:
    """Broker profile -> the provisioning.json the firmware reads (string values)."""
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise ProvisioningError(f"Profile not found: {path}") from exc
    except json.JSONDecodeError as exc:
        raise ProvisioningError(f"Invalid JSON in profile {path}: {exc}") from exc
    if not isinstance(raw, dict):
        raise ProvisioningError(f"Profile {path} must be a JSON object.")
    missing = [field for field in PROFILE_FIELDS if field not in raw]
    if missing:
        raise ProvisioningError(f"Profile {path} is missing: {', '.join(missing)}")
    host = raw["mqtt_uri"]
    if not isinstance(host, str) or not host.strip():
        raise ProvisioningError("Invalid profile field 'mqtt_uri': expected a non-empty host.")
    if len(host.strip()) >= 128:
        raise ProvisioningError("Invalid profile field 'mqtt_uri': at most 127 characters.")
    return {
        "mqtt_uri": host.strip(),
        "mqtt_port": normalize_port(raw["mqtt_port"]),
        "mqtt_use_tls": normalize_tls(raw["mqtt_use_tls"]),
    }


# --- backend API ------------------------------------------------------------------

class Api:
    def __init__(self, base_url: str, token: str):
        base = base_url.rstrip("/")
        self.root = base if base.endswith("/api") else f"{base}/api"
        self.token = token

    def call(self, method: str, path: str, payload: object | None = None) -> object:
        body = None if payload is None else json.dumps(payload).encode("utf-8")
        headers = {"Authorization": f"Bearer {self.token}", "Accept": "application/json"}
        if body is not None:
            headers["Content-Type"] = "application/json"
        http_request = request.Request(f"{self.root}{path}", data=body, method=method, headers=headers)
        try:
            with request.urlopen(http_request, timeout=30) as response:
                raw = response.read().decode("utf-8")
        except error.HTTPError as exc:
            detail = exc.read().decode("utf-8", errors="replace")
            hint = " (expired token? run provisioning/login.py)" if exc.code == 401 else ""
            raise ProvisioningError(f"{method} {path} failed with {exc.code}{hint}: {detail}") from exc
        except error.URLError as exc:
            raise ProvisioningError(f"Cannot reach the API at {self.root}: {exc.reason}") from exc
        return json.loads(raw) if raw else None

    def get(self, path: str) -> object:
        return self.call("GET", path)

    def post(self, path: str, payload: object) -> object:
        return self.call("POST", path, payload)

    def put(self, path: str, payload: object) -> object:
        return self.call("PUT", path, payload)

    def patch(self, path: str, payload: object) -> object:
        return self.call("PATCH", path, payload)


def find_device(api: Api, serial: str) -> dict | None:
    query = parse.urlencode({"search": serial, "per_page": 50})
    for device in api.get(f"/devices?{query}").get("items") or []:
        if device.get("serial") == serial:
            return device
    return None


def sensor_catalog(api: Api) -> dict[str, dict]:
    """Active sensor models by code."""
    return {sensor["code"]: sensor for sensor in api.get("/sensor-catalog/sensors")}


def environmental_type_id(api: Api) -> str:
    query = parse.urlencode({"search": ENVIRONMENTAL_TYPE_CODE, "per_page": 50})
    for device_type in api.get(f"/devices/types?{query}").get("items") or []:
        if device_type.get("code") == ENVIRONMENTAL_TYPE_CODE:
            return device_type["id"]
    raise ProvisioningError(f"Device type {ENVIRONMENTAL_TYPE_CODE!r} not found or inactive.")


def plan_sensor_changes(installed: list[dict], codes_by_sensor_id: dict[str, str], sensor: str) -> list[tuple]:
    """Steps that leave exactly one active installation of `sensor`, keyed `sensor`.

    ("deactivate", row) for every other active installation (first, so the type's
    per-model maximum never blocks the swap), then ("reactivate", row) for an
    inactive row of the same model already keyed `sensor`, or ("install", None).
    A `sensor` key held by another model (inactive history alias) is an error:
    the firmware publishes that exact key.
    """
    steps: list[tuple] = []
    target = None
    for row in installed:
        is_target = row["key"] == sensor and codes_by_sensor_id.get(row["sensorId"]) == sensor
        if is_target:
            target = row
        elif row["isActive"]:
            steps.append(("deactivate", row))
        if row["key"] == sensor and not is_target:
            raise ProvisioningError(
                f"Sensor key {sensor!r} already belongs to another model on this device; "
                "rename that installation from the web app first."
            )
    if target is None:
        steps.append(("install", None))
    elif not target["isActive"]:
        steps.append(("reactivate", target))
    return steps


def reconcile_sensors(api: Api, device_id: str, sensor: str, catalog: dict[str, dict]) -> list[str]:
    if sensor not in catalog:
        raise ProvisioningError(f"Sensor model {sensor!r} is not in the active sensor catalog.")
    codes = {model["id"]: code for code, model in catalog.items()}
    installed = api.get(f"/devices/{device_id}/sensors")
    log = []
    for action, row in plan_sensor_changes(installed, codes, sensor):
        if action == "deactivate":
            api.patch(f"/devices/{device_id}/sensors/{row['id']}", {"isActive": False})
            log.append(f"removed sensor {row['key']}")
        elif action == "reactivate":
            api.patch(f"/devices/{device_id}/sensors/{row['id']}", {"isActive": True})
            log.append(f"reactivated sensor {sensor}")
        else:
            api.post(f"/devices/{device_id}/sensors", {"sensorId": catalog[sensor]["id"], "key": sensor})
            log.append(f"installed sensor {sensor}")
    return log


def ensure_device(api: Api, args: argparse.Namespace, catalog: dict[str, dict]) -> tuple[dict, list[str]]:
    label = SENSORS[args.sensor]
    log: list[str] = []
    if args.serial:
        device = find_device(api, args.serial)
        if device is None:
            device = api.post("/devices", {
                "serial": args.serial,
                "name": args.name or f"{label} {args.serial}",
                "sensors": [{"sensorId": catalog[args.sensor]["id"], "key": args.sensor}],
            })
            log.append("registered with POST /api/devices")
        else:
            log.append("existing device")
    else:
        payload = {key: value for key, value in (
            ("model", args.model), ("batch", args.batch), ("manufactureDate", args.manufacture_date),
            ("name", args.name),
        ) if value}
        payload["sensors"] = [{"sensorId": catalog[args.sensor]["id"], "key": args.sensor}]
        device = api.post("/provisioning/devices/prepare", payload)
        log.append("serial reserved with POST /api/provisioning/devices/prepare")
        if not args.name:
            args.name = f"{label} {device['serial']}"

    changes: dict[str, object] = {}
    if args.name and device.get("name") != args.name:
        changes["name"] = args.name
    if (device.get("type") or {}).get("code") != ENVIRONMENTAL_TYPE_CODE:
        changes["deviceTypeId"] = environmental_type_id(api)
    if changes:
        device = api.put(f"/devices/{device['id']}", changes)
        log.append("updated " + ", ".join(sorted(changes)))
    return device, log


def resolve_environment_id(api: Api, args: argparse.Namespace) -> str | None:
    if args.environment_id:
        return args.environment_id
    if args.environment_of:
        reference = find_device(api, args.environment_of)
        if reference is None or not reference.get("environmentId"):
            raise ProvisioningError(f"{args.environment_of} is not paired to an environment.")
        return reference["environmentId"]
    return None


def ensure_environment(api: Api, device: dict, environment_id: str | None) -> tuple[dict, list[str]]:
    if environment_id is None:
        return device, []
    current = device.get("environmentId")
    if current == environment_id:
        return device, []
    if current is None:
        device = api.post("/devices/pair", {
            "serial": device["serial"], "environmentId": environment_id,
            "description": device.get("name") or device["serial"],
        })
        return device, [f"paired to environment {environment_id}"]
    print(f"Warning: {device['serial']} already belongs to environment {current}; "
          "not moved (use the web app to move it).", file=sys.stderr)
    return device, []


# --- certificates and staging -------------------------------------------------

def run(command: list[str], **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(command, check=True, capture_output=True, text=True, **kwargs)


def check_certificate(cert_dir: Path, ca_cert: Path, serial: str) -> None:
    for name in CERT_FILES:
        if not (cert_dir / name).is_file():
            raise ProvisioningError(f"Missing {cert_dir / name}")
    try:
        run(["openssl", "verify", "-CAfile", str(ca_cert), str(cert_dir / "client.crt")])
    except subprocess.CalledProcessError as exc:
        raise ProvisioningError(f"{cert_dir / 'client.crt'} is not signed by {ca_cert}: {exc.stdout}{exc.stderr}") from exc
    subject = run(["openssl", "x509", "-in", str(cert_dir / "client.crt"), "-noout",
                   "-subject", "-nameopt", "RFC2253"]).stdout.strip()
    cn = re.search(r"(?:^|[=,])CN=([^,]+)", subject.removeprefix("subject="))
    if cn is None or cn.group(1) != serial:
        raise ProvisioningError(f"{cert_dir / 'client.crt'} has {subject!r}, expected CN={serial}")
    cert_key = run(["openssl", "x509", "-in", str(cert_dir / "client.crt"), "-noout", "-pubkey"]).stdout
    private_key = run(["openssl", "pkey", "-in", str(cert_dir / "client.key"), "-pubout"]).stdout
    if cert_key.strip() != private_key.strip():
        raise ProvisioningError(f"{cert_dir / 'client.key'} does not match client.crt")


def ensure_certificates(pki_dir: Path, serial: str) -> tuple[Path, str]:
    ca_cert = pki_dir / "ca" / "ca.crt"
    if not ca_cert.is_file():
        raise ProvisioningError(f"CA not found at {ca_cert}: run mqtt/pki/crear-ca.sh first.")
    cert_dir = pki_dir / "devices" / serial
    if cert_dir.exists():
        status = "reused"
    else:
        try:
            run(["bash", str(pki_dir / "emitir-certificado-dispositivo.sh"), serial])
        except subprocess.CalledProcessError as exc:
            raise ProvisioningError(f"Certificate issuing failed: {exc.stderr or exc.stdout}") from exc
        status = "issued"
    check_certificate(cert_dir, ca_cert, serial)
    return cert_dir, status


def stage(staging_root: Path, serial: str, cert_dir: Path, ca_cert: Path, profile: dict[str, str]) -> Path:
    staged = staging_root / serial / "cert"
    staged.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ca_cert, staged / "root.crt")
    shutil.copyfile(cert_dir / "client.crt", staged / "client.crt")
    shutil.copyfile(cert_dir / "client.key", staged / "client.key")
    os.chmod(staged / "client.key", 0o600)
    (staged / "serial.txt").write_text(f"{serial}\n", encoding="utf-8")
    (staged / "provisioning.json").write_text(json.dumps(profile, indent=2) + "\n", encoding="utf-8")
    return staged


def copy_to_firmware(staged: Path, firmware_cert_dir: Path) -> None:
    firmware_cert_dir.mkdir(parents=True, exist_ok=True)
    for name in STAGED_FILES:
        shutil.copy2(staged / name, firmware_cert_dir / name)


def build_commands(sensor: str, port: str) -> list[str]:
    build_dir = f"build-{sensor}"
    return [
        f"source {IDF_ACTIVATE}",
        "cd esp32",
        # reconfigure: the LittleFS file list is fixed when CMake runs.
        f"idf.py -B {build_dir} -DCEIOT_SENSOR={sensor} reconfigure build",
        f"idf.py -B {build_dir} -p {port} erase-flash flash",
        f"idf.py -B {build_dir} -p {port} monitor",
    ]


def flash(sensor: str, port: str) -> None:
    build_dir = f"build-{sensor}"
    script = " && ".join([
        f"source {IDF_ACTIVATE} >/dev/null",
        f"cd {shlex.quote(str(FIRMWARE_DIR))}",
        f'"$IDF_PYTHON_ENV_PATH/bin/python" "$IDF_PATH/tools/idf.py" -B {build_dir} '
        f"-DCEIOT_SENSOR={sensor} reconfigure build",
        f'"$IDF_PYTHON_ENV_PATH/bin/python" "$IDF_PATH/tools/idf.py" -B {build_dir} '
        f"-p {shlex.quote(port)} erase-flash flash",
    ])
    subprocess.run(["bash", "-c", script], check=True)


# --- CLI ----------------------------------------------------------------------

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Provision a CEIoT environmental device (ESP32).")
    commands = parser.add_subparsers(dest="command", required=True)
    prepare = commands.add_parser(
        "prepare", help="Register/reconcile the device, issue its certificate and stage the firmware files.")
    prepare.add_argument("--sensor", required=True, choices=sorted(SENSORS),
                         help="Firmware variant and the single sensor installed on the device.")
    prepare.add_argument("--serial", type=normalize_serial,
                         help="Existing or desired serial (IOT-XXXX-XXXX). Omit to let the backend generate one.")
    prepare.add_argument("--name", help="Device name (default for new devices: '<SENSOR> <serial>').")
    environment = prepare.add_mutually_exclusive_group()
    environment.add_argument("--environment-id", help="Pair the device to this environment (UUID).")
    environment.add_argument("--environment-of", type=normalize_serial, metavar="SERIAL",
                             help="Pair the device to the environment of this other device.")
    prepare.add_argument("--model", help="Hardware model (generated serial only).")
    prepare.add_argument("--batch", help="Production batch (generated serial only).")
    prepare.add_argument("--manufacture-date", help="YYYY-MM-DD (generated serial only).")
    prepare.add_argument("--profile", type=Path, default=DEFAULT_PROFILE,
                         help="Broker profile JSON (default: provisioning/profiles/local.json).")
    prepare.add_argument("--pki-dir", type=Path, default=DEFAULT_PKI_DIR)
    prepare.add_argument("--staging-root", type=Path, default=DEFAULT_STAGING_ROOT)
    prepare.add_argument("--firmware-cert-dir", type=Path, default=DEFAULT_FIRMWARE_CERT_DIR)
    prepare.add_argument("--skip-firmware-copy", action="store_true",
                         help="Stage only; leave esp32/cert/ untouched.")
    prepare.add_argument("--port", default="/dev/ttyUSB0", help="Serial port for the printed flash command.")
    prepare.add_argument("--flash", metavar="PORT",
                         help="Also build the variant and run erase-flash + flash on PORT.")
    prepare.add_argument("--api-base-url")
    prepare.add_argument("--env-file", type=Path, default=DEFAULT_ENV_FILE)
    return parser


def run_prepare(args: argparse.Namespace) -> int:
    if args.serial and (args.model or args.batch or args.manufacture_date):
        raise ProvisioningError("--model/--batch/--manufacture-date only apply to a generated serial.")
    if args.flash and args.skip_firmware_copy:
        raise ProvisioningError("--flash needs the staged files in esp32/cert (drop --skip-firmware-copy).")
    env_values = parse_env_file(args.env_file)
    base_url = args.api_base_url or resolve_setting("CEIOT_API_BASE_URL", env_values, DEFAULT_API_BASE_URL)
    token = resolve_setting("CEIOT_API_TOKEN", env_values)
    if not token:
        raise ProvisioningError("Missing CEIOT_API_TOKEN: run provisioning/login.py first.")
    profile = load_profile(args.profile)
    api = Api(base_url, token)

    catalog = sensor_catalog(api)
    if args.sensor not in catalog:
        raise ProvisioningError(f"Sensor model {args.sensor!r} is not in the active sensor catalog.")
    environment_id = resolve_environment_id(api, args)
    device, log = ensure_device(api, args, catalog)
    serial = device["serial"]
    device, paired = ensure_environment(api, device, environment_id)
    log += paired
    if device.get("environmentId"):
        log += reconcile_sensors(api, device["id"], args.sensor, catalog)
    elif log[0] == "existing device":
        log.append("unpaired: installed sensors not checked (pair it with --environment-id/--environment-of)")

    cert_dir, cert_status = ensure_certificates(args.pki_dir, serial)
    staged = stage(args.staging_root, serial, cert_dir, args.pki_dir / "ca" / "ca.crt", profile)

    print(f"Device: {serial} ({device['id']}) - {device.get('name')}")
    for line in log:
        print(f"  - {line}")
    print(f"Sensor: {SENSORS[args.sensor]} (key {args.sensor})")
    print(f"Certificate: {cert_status} ({cert_dir}), CN={serial} verified against the CA")
    print(f"Broker: {profile['mqtt_uri']}:{profile['mqtt_port']} "
          f"(TLS {'on' if profile['mqtt_use_tls'] == '1' else 'off'}) from {args.profile}")
    print(f"Staged: {staged}")
    if args.skip_firmware_copy:
        print("Firmware cert dir: not updated (--skip-firmware-copy)")
    else:
        copy_to_firmware(staged, args.firmware_cert_dir)
        print(f"Firmware cert dir updated: {args.firmware_cert_dir} ({', '.join(STAGED_FILES)})")

    port = args.flash or args.port
    if args.flash:
        flash(args.sensor, args.flash)
        print(f"Flashed {serial} ({SENSORS[args.sensor]}) on {args.flash}. Monitor:")
        print(f"  {build_commands(args.sensor, port)[-1]}")
    else:
        print("Next (build + erase-flash + flash):")
        for command in build_commands(args.sensor, port):
            print(f"  {command}")
    return 0


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.command == "prepare":
        return run_prepare(args)
    raise ProvisioningError(f"Unsupported command: {args.command}")


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ProvisioningError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc
    except subprocess.CalledProcessError as exc:
        print(f"Error: command failed with exit code {exc.returncode}: {exc.cmd}", file=sys.stderr)
        raise SystemExit(1) from exc
